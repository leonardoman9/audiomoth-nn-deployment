/*
 * Generates firmware/bird/generated/bird_frontend_tables.h: the constant tables of the bird front-end
 * (FFT twiddles, bit reversal, filterbank taps), from the learned filterbank parameters of the checkpoint.
 * Host program; uses the same float formulas that were verified against PyTorch (check_frontend.py).
 *   cc -O2 gen_frontend_tables.c -lm -o gen && ./gen 3745.8291015625 92.80845642089844 150 16000 > bird_frontend_tables.h
 */
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#define PI_F 3.14159265358979323846f
#define NFFT 1024
#define BINS 513
#define MELS 64
#define SR   32000

static float Sigmoidf(float x) { return 1.0f / (1.0f + expf(-x)); }
static float Linspace01(int i, int n) {  /* torch.linspace(0,1,n) in float32 */
  const float step = 1.0f / (float)(n - 1);
  return i < n / 2 ? (float)i * step : 1.0f - (float)(n - 1 - i) * step;
}

int main(int argc, char** argv) {
  if (argc != 5) { fprintf(stderr, "usage: gen breakpoint transition_width f_min f_max\n"); return 2; }
  const float bp = strtof(argv[1], 0), tw = strtof(argv[2], 0), f_min = strtof(argv[3], 0), f_max = strtof(argv[4], 0);
  printf("/* Generated by tools/gen_frontend_tables.c (breakpoint %.4f Hz, transition width %.4f, %.0f-%.0f Hz). Do not edit. */\n", bp, tw, f_min, f_max);
  printf("#ifndef BIRD_FRONTEND_TABLES_H\n#define BIRD_FRONTEND_TABLES_H\n#include <stdint.h>\n\n");
  /* twiddles for N=1024: W^i = cos(2 pi i/N) - j sin(2 pi i/N) */
  printf("static const float kFeCos[512] = {");
  for (int i = 0; i < 512; ++i) printf("%s%.9ef", i ? "," : "", (double)cosf(-2.0f * PI_F * (float)i / (float)NFFT));
  printf("};\nstatic const float kFeSin[512] = {");
  for (int i = 0; i < 512; ++i) printf("%s%.9ef", i ? "," : "", (double)sinf(-2.0f * PI_F * (float)i / (float)NFFT));
  printf("};\nstatic const uint16_t kFeBitRev512[512] = {");
  for (int i = 0; i < 512; ++i) {
    unsigned r = 0, v = (unsigned)i;
    for (int b = 0; b < 9; ++b) { r = (r << 1) | (v & 1u); v >>= 1; }
    printf("%s%u", i ? "," : "", r);
  }
  printf("};\n");
  /* filterbank */
  float centre[MELS];
  const float f_range = f_max - f_min, norm_bp = (bp - f_min) / f_range, bin_per_hz = (float)(NFFT / 2) / ((float)SR / 2.0f);
  for (int m = 0; m < MELS; ++m) {
    const float x = Linspace01(m, MELS);
    const float log_part = f_min * powf(f_max / f_min, x), lin_part = f_min + x * f_range;
    const float s = Sigmoidf((x - norm_bp) * tw);
    float c = (1.0f - s) * log_part + s * lin_part;
    if (c < f_min) c = f_min;
    if (c > f_max) c = f_max;
    centre[m] = c * bin_per_hz;
  }
  const float f_min_bin = f_min * bin_per_hz, f_max_bin = f_max * bin_per_hz, eps = 1e-8f;
  static float w[4000]; unsigned start[MELS], len[MELS], off[MELS], used = 0;
  for (int m = 0; m < MELS; ++m) {
    const float left = m == 0 ? f_min_bin : centre[m - 1], right = m == MELS - 1 ? f_max_bin : centre[m + 1], c = centre[m];
    int k0 = (int)floorf(left), k1 = (int)ceilf(right);
    if (k0 < 0) k0 = 0;
    if (k1 > BINS - 1) k1 = BINS - 1;
    start[m] = (unsigned)k0; off[m] = used; len[m] = 0;
    for (int k = k0; k <= k1; ++k) {
      const float up = ((float)k - left) / ((c - left) + eps), down = (right - (float)k) / ((right - c) + eps);
      float v = up < down ? up : down;
      if (v < 0.0f) v = 0.0f;
      w[used++] = v; len[m]++;
    }
  }
  printf("#define BFE_FB_TAPS %u\n", used);
  printf("static const uint16_t kFeFbStart[%d] = {", MELS); for (int m = 0; m < MELS; ++m) printf("%s%u", m ? "," : "", start[m]);
  printf("};\nstatic const uint16_t kFeFbLen[%d] = {", MELS); for (int m = 0; m < MELS; ++m) printf("%s%u", m ? "," : "", len[m]);
  printf("};\nstatic const uint16_t kFeFbOffset[%d] = {", MELS); for (int m = 0; m < MELS; ++m) printf("%s%u", m ? "," : "", off[m]);
  printf("};\nstatic const float kFeFbWeight[%u] = {", used); for (unsigned i = 0; i < used; ++i) printf("%s%.9ef", i ? "," : "", (double)w[i]);
  printf("};\n\n#endif\n");
  return 0;
}
